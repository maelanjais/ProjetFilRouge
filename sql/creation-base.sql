-- creation-base.sql - crée toute la base de données de la messagerie dans un projet
-- Supabase vide : tables, vue, déclencheur, temps réel et règles RLS.
-- À exécuter une seule fois dans le SQL Editor d'un NOUVEAU projet : sur un projet
-- existant, les "create" échouent car les tables existent déjà.


-- =========================================================================
-- Tables
-- =========================================================================

-- ---- profils ----
-- Profil public de chaque compte : sert à la recherche de contacts et à l'affichage
-- du pseudo. L'id est celui de auth.users, ce qui permet d'écrire le RLS avec auth.uid().
create table public.profils (
  id uuid primary key references auth.users(id) on delete cascade,
  nom_utilisateur varchar not null
    check (char_length(nom_utilisateur) between 3 and 30),
  date_creation timestamptz not null default now()
);

-- Pseudo unique sans tenir compte des majuscules : « Thomas » et « thomas » ne
-- peuvent pas coexister.
create unique index profils_nom_utilisateur_unique
  on public.profils (lower(nom_utilisateur));

-- ---- contacts ----
-- Une ligne = proprietaire_id a ajouté contact_id (relation à sens unique).
-- La clé primaire composée empêche d'ajouter deux fois le même contact.
create table public.contacts (
  proprietaire_id uuid not null references public.profils(id) on delete cascade,
  contact_id uuid not null references public.profils(id) on delete cascade,
  date_creation timestamptz not null default now(),
  primary key (proprietaire_id, contact_id),
  check (proprietaire_id <> contact_id)
);

-- ---- salons ----
-- Conversation entre deux utilisateurs : cree_par (qui l'a ouverte) et
-- participant_id (son interlocuteur). Le nom affiché est le pseudo de l'autre
-- participant, lu dans profils : la colonne nom est facultative et inutilisée.
create table public.salons (
  id int8 generated by default as identity primary key,
  date_creation timestamptz not null default now(),
  nom varchar,
  cree_par uuid references public.profils(id) on delete set null,
  participant_id uuid references public.profils(id) on delete cascade,
  constraint salons_participants_differents check (cree_par <> participant_id)
);

-- ---- messages ----
-- auteur_pseudo est conservé pour afficher l'auteur même si son compte est supprimé.
-- Les messages vocaux sont stockés dans contenu sous forme d'URL.
create table public.messages (
  id int8 generated by default as identity primary key,
  date_creation timestamptz not null default now(),
  salon_id int8 not null references public.salons(id) on delete cascade,
  auteur_id uuid references public.profils(id) on delete set null,
  auteur_pseudo varchar,
  contenu text
);


-- =========================================================================
-- Vue
-- =========================================================================

-- Dernier message de chaque salon, pour l'aperçu dans la liste des conversations.
-- distinct on (salon_id) garde une seule ligne par salon : la première selon le
-- tri, donc la plus récente grâce à "date_creation desc".
-- security_invoker : la vue applique le RLS de messages pour l'utilisateur qui la
-- lit, et non les droits de son créateur.
create view public.derniers_messages
with (security_invoker = true) as
select distinct on (salon_id)
  salon_id, contenu, auteur_id, auteur_pseudo, date_creation
from public.messages
order by salon_id, date_creation desc;


-- =========================================================================
-- Création automatique du profil à l'inscription
-- =========================================================================

-- Le pseudo est lu dans les métadonnées envoyées par signUp (nom_utilisateur).
-- security definer : la fonction peut écrire dans profils malgré le RLS.
-- search_path vide : évite qu'une table homonyme d'un autre schéma soit utilisée.
create function public.creer_profil_utilisateur()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profils (id, nom_utilisateur)
  values (new.id, new.raw_user_meta_data ->> 'nom_utilisateur');
  return new;
end;
$$;

create trigger declencheur_creer_profil
  after insert on auth.users
  for each row execute function public.creer_profil_utilisateur();


-- =========================================================================
-- Temps réel
-- =========================================================================

-- Sans cette ligne, les nouveaux messages n'arrivent pas en direct chez
-- l'interlocuteur.
alter publication supabase_realtime add table public.messages;


-- =========================================================================
-- Row Level Security : chaque utilisateur ne lit et n'écrit que ce qui le concerne
-- =========================================================================
-- (select auth.uid()) plutôt que auth.uid() : évalué une seule fois par requête.
-- Sans règle pour une opération (update, delete...), elle est interdite.

alter table public.profils  enable row level security;
alter table public.contacts enable row level security;
alter table public.salons   enable row level security;
alter table public.messages enable row level security;

-- ---- profils ----
-- Lecture ouverte, même sans être connecté : la page d'inscription vérifie que le
-- pseudo est libre avant la création du compte. La table ne contient que des pseudos.
-- Pas de règle d'ajout : seul le déclencheur (security definer) crée les profils.
create policy "Profils lisibles par tous" on public.profils
  for select to anon, authenticated using (true);

create policy "Modifier son propre profil" on public.profils
  for update to authenticated
  using (id = (select auth.uid()))
  with check (id = (select auth.uid()));

-- ---- contacts ----
create policy "Lire ses contacts" on public.contacts
  for select to authenticated using (proprietaire_id = (select auth.uid()));

create policy "Ajouter un contact" on public.contacts
  for insert to authenticated with check (proprietaire_id = (select auth.uid()));

create policy "Supprimer un contact" on public.contacts
  for delete to authenticated using (proprietaire_id = (select auth.uid()));

-- ---- salons ----
-- Visible par ses deux participants ; on ne peut créer un salon qu'à son propre nom.
create policy "Lire ses salons" on public.salons
  for select to authenticated
  using ((select auth.uid()) in (cree_par, participant_id));

create policy "Créer un salon" on public.salons
  for insert to authenticated with check (cree_par = (select auth.uid()));

-- ---- messages ----
-- Lire et écrire uniquement dans les salons dont on est participant ; on ne peut
-- écrire qu'en son propre nom (auteur_id).
create policy "Lire les messages de ses salons" on public.messages
  for select to authenticated
  using (exists (
    select 1 from public.salons s
    where s.id = messages.salon_id
      and (select auth.uid()) in (s.cree_par, s.participant_id)
  ));

create policy "Écrire dans ses salons" on public.messages
  for insert to authenticated
  with check (
    auteur_id = (select auth.uid())
    and exists (
      select 1 from public.salons s
      where s.id = messages.salon_id
        and (select auth.uid()) in (s.cree_par, s.participant_id)
    )
  );
